#pragma once


// STL includes
#include <functional>
#include <memory>

// Qt includes
#include <QtCore/QMetaObject>
#include <QtCore/QObject>

// ACF includes
#include <icomp/IRegistryElement.h>
#include <iprm/IParamsSet.h>

// ImtCore includes
#include <imtrest/IRequestServlet.h>
#include <imtrest/IServer.h>
#include <imtrestdemo/IDemoSettingsController.h>


namespace imtrestdemo
{


/**
	The components of the demo server that the code of the server needs. The composition of the server is described by the partitura
	Impl/ImtRestDemoServer/ImtRestDemoServer.acc, the class of it (CImtRestDemoServer) is generated by ARXC in the project that uses
	the server (the application and the tests), so the code of the library works with it through this interface.
*/
class IDemoComposition
{
public:
	virtual ~IDemoComposition() = default;

	/**
		TCP server (the component \c TcpServer of the partitura).
	*/
	virtual imtrest::IServer* GetServer() = 0;

	/**
		Component \c SettingsController: the code of the server gives it the functions of the settings.
	*/
	virtual IDemoSettingsControllerBinding* GetSettingsController() = 0;

	/**
		Parameters of the TLS (the component \c TlsConfiguration).
	*/
	virtual iprm::IParamsSet* GetTlsParameters() = 0;

	/**
		Close all connections and stop the worker threads, the call returns when they are finished. A request that still works must not
		use the components that are going to be destroyed, so the owner of the composition calls it before.
	*/
	virtual void ShutdownConnections() = 0;
};


/**
	Creates the composition. The element has the values of the exported attributes of the partitura (port, token, directories, ...).
*/
typedef std::function<std::unique_ptr<IDemoComposition>(const icomp::IRegistryElement& settingsElement)> DemoCompositionFactory;


/**
	Adapter of a class that ARXC has generated from ImtRestDemoServer.acc.
*/
template <class Composition>
class TDemoComposition: virtual public IDemoComposition
{
public:
	explicit TDemoComposition(const icomp::IRegistryElement& settingsElement)
		:m_composition(&settingsElement)
	{
	}

	// reimplemented (IDemoComposition)
	virtual imtrest::IServer* GetServer() override
	{
		return m_composition.template GetInterface<imtrest::IServer>("TcpServer");
	}

	virtual IDemoSettingsControllerBinding* GetSettingsController() override
	{
		return m_composition.template GetInterface<IDemoSettingsControllerBinding>("SettingsController");
	}

	virtual iprm::IParamsSet* GetTlsParameters() override
	{
		return m_composition.template GetInterface<iprm::IParamsSet>("TlsConfiguration");
	}

	virtual void ShutdownConnections() override
	{
		// The components do it when the application quits, their slots are called here (a slot can be called by the name)
		if (QObject* serverPtr = dynamic_cast<QObject*>(GetServer())){
			for (QObject* childPtr : serverPtr->children()){
				if (childPtr->metaObject()->indexOfMethod("ShutdownServer()") >= 0){
					QMetaObject::invokeMethod(childPtr, "ShutdownServer", Qt::DirectConnection);
				}
			}
		}

		if (QObject* managerPtr = dynamic_cast<QObject*>(m_composition.template GetInterface<imtrest::IRequestServlet>("WorkerManager"))){
			QMetaObject::invokeMethod(managerPtr, "AboutToQuit", Qt::DirectConnection);
		}
	}

private:
	Composition m_composition;
};


/**
	Get the factory of the compositions of the class that ARXC has generated from ImtRestDemoServer.acc.
*/
template <class Composition>
DemoCompositionFactory CreateDemoCompositionFactory()
{
	return [](const icomp::IRegistryElement& settingsElement){
		return std::unique_ptr<IDemoComposition>(new TDemoComposition<Composition>(settingsElement));
	};
}


} // namespace imtrestdemo
