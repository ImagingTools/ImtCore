/**
	Byte of the generated body at a position. The body of \c /stream is generated by the server, so a client
	can check any received range without keeping the whole body.
*/
inline quint8 GetPatternByte(qint64 position)
{
	return quint8((position * 131 + (position >> 8) * 7 + 17) & 0xFF);
}


/**
	Create a range of the generated body.
*/
QByteArray CreatePatternData(qint64 offset, qint64 length);


