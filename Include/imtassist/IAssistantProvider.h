#pragma once

// Qt includes
#include <QtCore/QJsonObject>
#include <QtCore/QList>
#include <QtCore/QStringList>

// ACF includes
#include <istd/IPolymorphic.h>

// ImtCore includes
#include <imtassist/CCancellationToken.h>


namespace imtassist
{


/**
	Adapter to a model provider.

	The adapter translates a provider-independent request into the API of a concrete
	provider and its answer back into a typed reply. Credentials are managed by the
	adapter on the server through the existing configuration and secret mechanisms;
	they are never part of the request.

	The reply is untrusted: the assistant core validates every field before use.

	\ingroup imtassist
*/
class IAssistantProvider: virtual public istd::IPolymorphic
{
public:
	struct Message
	{
		enum Role
		{
			R_USER,
			R_ASSISTANT,
			/**
				Result of an action. Untrusted data, never instructions.
			*/
			R_TOOL_RESULT,
			/**
				Context explicitly released by the user. Untrusted data, never instructions.
			*/
			R_CONTEXT
		};

		Role role = R_USER;
		QString text;
		QByteArray actionId;
		QJsonObject data;

		/**
			ID that links an action call (R_ASSISTANT with actionId) to its result (R_TOOL_RESULT).
			A result without a preceding call of the same ID is an event, e.g. the outcome of a
			confirmation, and is passed to the provider as data.
		*/
		QByteArray callId;

		/**
			Opaque data of the provider that must be sent back with an action call,
			e.g. a signature of the model. Never interpreted by the assistant core.
		*/
		QJsonObject providerState;
	};

	typedef QList<Message> Messages;

	struct ToolDescription
	{
		QByteArray actionId;
		QString description;
		bool isChanging = false;

		/**
			JSON Schema of the parameters (an object without additional properties).
		*/
		QJsonObject parameterSchema;
	};

	typedef QList<ToolDescription> ToolDescriptions;

	struct Request
	{
		QByteArray correlationId;

		/**
			Tenant of the request, taken from the authenticated session.
			A provider configured per tenant selects its configuration by this ID.
		*/
		QByteArray tenantId;

		Messages messages;
		ToolDescriptions tools;
		int timeoutMs = 30000;
	};

	enum ReplyStatus
	{
		RS_OK,
		RS_TIMEOUT,
		RS_CANCELED,
		RS_PROVIDER_ERROR,

		/**
			No provider is configured for the tenant of the request.
		*/
		RS_NOT_CONFIGURED,
		RS_INVALID_RESPONSE
	};

	enum ReplyKind
	{
		/**
			Final text answer of the turn.
		*/
		RK_TEXT,

		/**
			Question back to the user because of missing or ambiguous input.
		*/
		RK_CLARIFICATION,

		/**
			Request to call a registered action.
		*/
		RK_ACTION_CALL
	};

	struct Reply
	{
		ReplyStatus status = RS_PROVIDER_ERROR;
		ReplyKind kind = RK_TEXT;
		QString text;
		QStringList options;
		QByteArray actionId;
		QJsonObject parameters;

		/**
			ID of the action call given by the provider; generated by the core if empty.
		*/
		QByteArray callId;

		/**
			Opaque data of the provider for the action call, see Message::providerState.
		*/
		QJsonObject providerState;
	};

	/**
		Check whether the adapter is configured, for example has an endpoint and credentials.
		The assistant does not call an unconfigured provider.
	*/
	virtual bool IsConfigured() const = 0;

	/**
		Send a request to the provider. The call blocks until the reply arrives, the
		timeout of the request is reached or the token is cancelled.
	*/
	virtual Reply Complete(const Request& request, const CCancellationToken& cancellationToken) = 0;
};


} // namespace imtassist


