// Writes tests/diff/cases/controls_api.qml: for each control of QtQuick.Controls the runtime has, every property of its
// Qt 6.12 API (plugins.qmltypes of QtQuick.Templates, from QQuickControl down) with its default value, and whether each of
// its signals and methods is there. Run it again when a control is added:
//   node tests/diff/tools/gen_controls_api.js [qml dir of Qt]
const fs = require('fs')
const os = require('os')
const path = require('path')
const { parse, api } = require('./qmltypes')
const { CONTROLS } = require('../../../Runtime/Qt/modules')

const qml = process.argv[2] || path.join(os.homedir(), 'Qt/6.12.0/macos/qml')
const components = parse(path.join(qml, 'QtQuick/Templates/plugins.qmltypes'))
// the table controls have cases of their own; values that differ by font or platform are left out
const SKIP_TYPES = new Set(['Overlay', 'HorizontalHeaderView', 'VerticalHeaderView', 'TableViewDelegate', 'TreeViewDelegate', 'SelectionRectangle'])
const SKIP_PROPS = new Set(['locale', 'font', 'palette'])
// the sizes of a text (an empty one too) depend on the font of the platform: printed on a line of their own (text:), which
// a v5 build on another platform may print otherwise
const TEXT_METRICS = new Set(['baselineOffset', 'implicitContentWidth', 'implicitContentHeight', 'implicitLabelHeight', 'implicitLabelWidth', 'implicitWidth', 'implicitHeight', 'height', 'contentHeight', 'availableHeight'])
const TEXT_TYPES = new Set(['Label', 'CheckBox', 'RadioButton', 'Switch', 'DelayButton', 'SpinBox', 'GroupBox', 'TextField', 'TextArea', 'ComboBox', 'ToolTip'])
// properties that hold an object: printed as null or object
const isObject = (p) => p.pointer || p.list || /^Q(Font|Locale|QuickIcon|Color|JSValue|Variant|Object)$|^QQuick|Component|QRectF|QPointF|QSizeF/.test(p.type) && p.type !== 'QColor'

let types = CONTROLS.filter(name => !SKIP_TYPES.has(name))
let entries = types.map(name => {
    let { props, signals, methods } = api(components, name, 'QQuickItem')
    // QQuickLabel derives from QQuickText: its own part only
    if(name === 'Label') ({ props, signals, methods } = api(components, name, 'QQuickText'))
    if(name === 'TextField') ({ props, signals, methods } = api(components, name, 'QQuickTextInput'))
    if(name === 'TextArea') ({ props, signals, methods } = api(components, name, 'QQuickTextEdit'))
    let metric = (p) => TEXT_TYPES.has(name) && TEXT_METRICS.has(p.name)
    props = props.filter(p => !p.name.startsWith('__'))
    let scalar = props.filter(p => !SKIP_PROPS.has(p.name) && !isObject(p) && !metric(p)).map(p => p.name)
    let objects = props.filter(p => !SKIP_PROPS.has(p.name) && isObject(p)).map(p => p.name)
    return { name, scalar: [...new Set(scalar)], objects: [...new Set(objects)], signals: [...new Set(signals)], methods: [...new Set(methods)] }
})

let out = `import QtQuick
import QtQuick.Controls

// Generated by tests/diff/tools/gen_controls_api.js from the plugins.qmltypes of Qt 6.12: the API of each control and the
// defaults of its properties (no text: a size of a text depends on the fonts)
Item {
    id: root
    width: 800
    height: 600
${types.map((name, i) => `    ${name} { id: c${i} }`).join('\n')}

    property var types: ${JSON.stringify(entries, null, 0).replace(/"(\w+)":/g, '$1:')}

    function show(v) {
        if (v === undefined) return "undefined"
        if (v === null) return "null"
        if (typeof v === "number") return String(Math.round(v * 1000) / 1000)
        return String(v)
    }
    Component.onCompleted: {
        let items = [${types.map((_, i) => 'c' + i).join(', ')}]
        for (let i = 0; i < items.length; i++) {
            let c = items[i], t = types[i]
            console.log(t.name, "scalars:", t.scalar.map(n => n + "=" + show(c[n])).join(" "))
            console.log(t.name, "objects:", t.objects.map(n => n + "=" + (c[n] === null || c[n] === undefined ? show(c[n]) : "object")).join(" "))
            console.log(t.name, "signals:", t.signals.filter(n => typeof c[n] !== "function").join(" ") || "all")
            console.log(t.name, "methods:", t.methods.filter(n => typeof c[n] !== "function").join(" ") || "all")
            console.log(t.name, "size:", ${'"'}${'"'} + (${JSON.stringify([...TEXT_TYPES])}.indexOf(t.name) >= 0 ? "(text)" : c.implicitWidth + " " + c.implicitHeight), "font:", c.font ? [c.font.pixelSize, c.font.bold, c.font.weight].join(" ") : "-",
                        "icon:", c.icon ? [c.icon.name, c.icon.source, c.icon.width, c.icon.height, c.icon.color, c.icon.cache].join(",") : "-")
        }
        Qt.quit()
    }
}
`
fs.writeFileSync(path.join(__dirname, '../cases/controls_api.qml'), out)
console.log('controls_api.qml:', types.join(' '))
